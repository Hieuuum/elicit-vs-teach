"""Generates the ts38fs target-stage overlay configs (EXPERIMENTS TBD,
"ts38fs format-install dose sweep").

ts38fs is a 3-axis grid — install size i in {1000, 4642, 21544, 100000},
target size n in {1000, 4642, 21544, 100000, 316228}, seed s in
{316, 1316, 2316} — 60 (i, n, s) cells. The (i=21544, s=316) column (5
cells, one per n) is REUSED from the already-shipped ts38pf family
(evt-ts38pf-preteachfmt-n<n>, ts38pf_preteachfmt.yaml's own committed
overlays) and is never retrained here, leaving 55 NEW cells.

Unlike every other ts38(*) family, whose per-size overlays are hand-authored
and committed one file at a time (5-8 files each), ts38fs's 55 cells make
that impractical to keep correct by hand — the same failure mode
test_fig2nl_overlays.py guards against (a transposed row in a hand-
transcribed per-size schedule parses fine and fails silently at cost, not
launch). This module is the single source of truth for the grid instead:
launch_ts38fs_family.sh calls ``write_overlays`` as an early preflight step
(before ANY training spend — a missing/wrong overlay must surface before
GPU time, not after), and the resulting files are read the same way every
other family's committed overlays are (``train_target.py --override
<path>``). ``cells``/``overlay_doc`` are also the direct target of this
module's own test coverage — no need to round-trip through the filesystem
to check the grid shape.

Usage:
    python3 generate_ts38fs_overlays.py --out ../configs/sweeps/ts38
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml

INSTALLS = (1000, 4642, 21544, 100000)
SIZES = (1000, 4642, 21544, 100000, 316228)
SEEDS = (316, 1316, 2316)

REUSED_INSTALL = 21544
REUSED_SEED = 316
PF_PARENT_RUN_ID = "evt-ts38pf-preteachfmt-parent"

# n -> (eval_every, max_steps, min_steps), transcribed verbatim from the
# already-shipped ts38pf family's own 5 committed overlays
# (configs/sweeps/ts38/ts38pf_preteachfmt_n<n>.yaml) — same target-size
# grid, same recipe; ts38fs only adds the install-size and seed axes.
STEP_SCHEDULE: dict[int, tuple[int, int, int]] = {
    1000: (5, 1000, 8),
    4642: (5, 1000, 37),
    21544: (25, 5000, 169),
    100000: (125, 15625, 782),
    316228: (375, 50000, 2471),
}


def cells() -> list[tuple[int, int, int]]:
    """Every (i, n, s) cell this family trains, in LAUNCH ORDER: seed s
    outer (a complete 1-seed sweep lands first), then install i ascending,
    then target n ascending (density first, seeds last) — excluding the 5
    reused (i=21544, s=316) cells. Always 55 entries (3*4*5 - 5)."""
    out = []
    for s in SEEDS:
        for i in INSTALLS:
            if i == REUSED_INSTALL and s == REUSED_SEED:
                continue
            for n in SIZES:
                out.append((i, n, s))
    return out


def parent_run_id_for(install: int) -> str:
    """The theta0 parent run id for install size ``install`` — the reused
    ts38pf parent at i=21544, else this family's own new
    evt-ts38fs-parent-n<i>."""
    return PF_PARENT_RUN_ID if install == REUSED_INSTALL else f"evt-ts38fs-parent-n{install}"


def run_id_for(install: int, n: int, seed: int) -> str:
    return f"evt-ts38fs-i{install}-n{n}-s{seed}"


def overlay_filename(install: int, n: int, seed: int) -> str:
    return f"ts38fs_i{install}_n{n}_s{seed}.yaml"


def overlay_doc(install: int, n: int, seed: int) -> dict:
    """The overlay body for one (install, n, seed) cell — deep-merged over
    ts38fs_target.yaml by train_target.py's ``--override``."""
    eval_every, max_steps, min_steps = STEP_SCHEDULE[n]
    return {
        "run_id": run_id_for(install, n, seed),
        "experiment": {"parent_run_id": parent_run_id_for(install)},
        "data": {"n_examples": n, "seed": seed},
        "train": {
            "seed": seed,
            "eval_every": eval_every,
            "max_steps": max_steps,
            "stopping": {"min_steps": min_steps},
        },
    }


def write_overlays(out_dir: Path) -> list[Path]:
    """Materialize all 55 overlay files under ``out_dir`` (idempotent —
    re-running overwrites with byte-identical content, since ``cells()`` and
    ``overlay_doc`` are pure functions of the module-level grid constants).
    Returns the written paths in launch order."""
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []
    for i, n, s in cells():
        doc = overlay_doc(i, n, s)
        header = (
            f"# ts38fs target-stage cell: install i={i}, target n={n}, seed s={s}.\n"
            f"# MACHINE-GENERATED by generate_ts38fs_overlays.py — do not hand-edit;\n"
            f"# regenerate instead. Overlay over ../../ts38fs_target.yaml.\n"
            f"# parent_run_id: {doc['experiment']['parent_run_id']}"
            f"{' (REUSED ts38pf parent)' if i == REUSED_INSTALL else ' (NEW ts38fs parent)'}\n"
        )
        path = out_dir / overlay_filename(i, n, s)
        path.write_text(header + yaml.safe_dump(doc, sort_keys=False))
        paths.append(path)
    return paths


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--out", type=Path, required=True, help="configs/sweeps/ts38 dir")
    args = ap.parse_args()
    paths = write_overlays(args.out)
    print(f"[ts38fs] wrote {len(paths)} overlays to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
